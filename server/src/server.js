import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import mongoose from 'mongoose';
import authRoutes from './routes/auth.js';
import productRoutes from './routes/products.js';
import orderRoutes from './routes/orders.js';
import adminRoutes from './routes/admin.js';

const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173'}));
app.use(express.json({limit:'100kb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,max:300,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({ok:true,service:'Mohlay Fashion API'}));
app.use('/api/auth',authRoutes);
app.use('/api/products',productRoutes);
app.use('/api/orders',orderRoutes);
app.use('/api/admin',adminRoutes);
app.use((err,_req,res,_next)=>{console.error(err);res.status(err.status||500).json({message:process.env.NODE_ENV==='production'?'Something went wrong.':err.message||'Server error'});});
const port=process.env.PORT||5000;
mongoose.connect(process.env.MONGODB_URI).then(()=>{app.listen(port,()=>console.log(`Mohlay API listening on ${port}`));}).catch(err=>{console.error('MongoDB connection failed:',err.message);process.exit(1);});
